"""Доменные ошибки. Модули бросают их, main.py превращает в ответ по формату контракта."""


class NotFound(Exception):
    """404: нет класса, урока, ученика, результата."""


class Conflict(Exception):
    """409: действие сейчас невозможно — например, домашка до пакета урока."""


class BadRequest(Exception):
    """400: некорректный ввод — например, балл больше максимума."""
